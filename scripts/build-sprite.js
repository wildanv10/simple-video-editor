// Rebuilds the inline SVG sprite in index.html from the files in icons/.
// Usage: node scripts/build-sprite.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const iconsDir = path.join(root, 'icons');
const htmlFile = path.join(root, 'index.html');

const symbols = fs.readdirSync(iconsDir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const svg = fs.readFileSync(path.join(iconsDir, f), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
    return `  <symbol id="i-${path.basename(f, '.svg')}" viewBox="0 0 24 24">${inner}</symbol>`;
  });

const sprite = [
  '<!-- sprite:start (generated by scripts/build-sprite.js) -->',
  '<svg class="sprite" width="0" height="0" aria-hidden="true">',
  ...symbols,
  '</svg>',
  '<!-- sprite:end -->',
].join('\n');

const html = fs.readFileSync(htmlFile, 'utf8');
const pattern = /<!-- sprite:start[\s\S]*?<!-- sprite:end -->/;
if (!pattern.test(html)) throw new Error('sprite markers not found in index.html');
fs.writeFileSync(htmlFile, html.replace(pattern, () => sprite));
console.log(`Sprite updated with ${symbols.length} icons.`);
